// Verify the offline checklist in an isolated browser; never alter user progress.
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const {pathToFileURL} = require('node:url');
const playwright = require(process.env.FAP_PLAYWRIGHT_PATH || 'playwright');
const root = path.resolve(__dirname, '../..');
const base = path.join(root, 'docs/research-platform');
const plan = JSON.parse(fs.readFileSync(path.join(base, 'checklist-10-tuan-v4.json'), 'utf8'));
const html = fs.readFileSync(path.join(base, 'checklist-10-tuan-v4.html'), 'utf8');
assert.deepEqual(JSON.parse(html.match(/<script id="plan-data" type="application\/json">(.*?)<\/script>/s)[1]), plan);
assert.equal(plan.weeks.length, 10);
assert.equal(plan.weeks.reduce((sum,w)=>sum+w.hours,0),195);
assert.equal(new Set(plan.weeks.flatMap(w=>w.tasks.map(t=>t.id))).size,60);
assert.equal(plan.version,6);
assert.equal(plan.weeks.filter(w=>w.reporting.word.length===3&&w.reporting.slides.length===4&&w.reporting.demo&&w.reporting.ask).length,10);
const qa = path.join(root, '_plan_render/plan-v4');
fs.mkdirSync(qa, {recursive:true});

(async()=>{
 const options = {headless:true};
 if(process.env.FAP_CHROMIUM_PATH)options.executablePath=process.env.FAP_CHROMIUM_PATH;
 const browser = await playwright.chromium.launch(options);
 try{
  const context = await browser.newContext({viewport:{width:1280,height:1000}});
  const page = await context.newPage(),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(pathToFileURL(path.join(base,'checklist-10-tuan-v4.html')).href);
  assert.equal(await page.locator('input[type=checkbox]').count(),60);
  assert.equal(await page.locator('input[type=checkbox]:checked').count(),0);
  assert.equal(await page.locator('.report-guide').count(),10);
  await page.locator('#start').fill('2026-10-12');
  await page.locator('#start').dispatchEvent('change');
  await page.locator('#W01-01').check();
  await page.locator('#notes-1').fill('Paddle: ảnh thật; còn kiểm đơn vị.');
  await page.locator('#hours-1').fill('2.5');
  await page.locator('#hours-1').dispatchEvent('change');
  await page.reload();
  assert.equal(await page.locator('#W01-01').isChecked(),true);
  assert.equal(await page.locator('#notes-1').inputValue(),'Paddle: ảnh thật; còn kiểm đơn vị.');
  assert.equal(await page.locator('#hours-1').inputValue(),'2.5');
  assert.match(await page.locator('#date-1').textContent(),/12\/10\/2026.*18\/10\/2026/);
  const download=page.waitForEvent('download');
  await page.locator('#export').click();await download;
  const backup=JSON.parse(await page.locator('#backup-json').inputValue());
  assert.equal(backup.checked['W01-01'],true);
  assert.equal(backup.actualHours['1'],2.5);
  await page.locator('#W01-01').uncheck();
  await page.locator('#paste-json').fill(JSON.stringify(backup));
  await page.locator('#import-text').click();
  assert.equal(await page.locator('#W01-01').isChecked(),true);
  await page.locator('#paste-json').fill(JSON.stringify({...backup,project:'old-13-week-project'}));
  await page.locator('#import-text').click();
  assert.match(await page.locator('#backup-status').textContent(),/Không nhập được/);
  assert.equal(await page.locator('#W01-01').isChecked(),true);
  await page.locator('#paste-json').fill(JSON.stringify({...backup,start:'2026-02-30'}));
  await page.locator('#import-text').click();
  assert.match(await page.locator('#backup-status').textContent(),/Không nhập được/);
  await page.locator('#import-file').setInputFiles({name:'backup.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(backup))});
  await page.waitForFunction(()=>document.getElementById('backup-status').textContent.startsWith('Đã nhập'));
  assert.equal(await page.locator('#W01-01').isChecked(),true);
  await page.locator('#backup-panel').evaluate(el=>el.open=false);
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:path.join(qa,'desktop.png'),fullPage:false});
  await page.locator('.report-guide').first().screenshot({path:path.join(qa,'word-slide-week-01.png')});
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.screenshot({path:path.join(qa,'mobile.png'),fullPage:false});
  await page.locator('#week-1').scrollIntoViewIfNeeded();
  await page.locator('#week-1').screenshot({path:path.join(qa,'week-01-mobile.png')});
  await page.evaluate(()=>window.dispatchEvent(new Event('beforeprint')));
  assert.equal(await page.locator('.week[open]').count(),10);
  await page.evaluate(()=>window.dispatchEvent(new Event('afterprint')));
  assert.equal(await page.locator('.week[open]').count(),1);
  // localStorage disabled should display a warning while retaining in-memory state.
  const blocked=await browser.newContext();
  await blocked.addInitScript(()=>{Object.defineProperty(Storage.prototype,'setItem',{value(){throw new Error('blocked');}});});
  const fallback=await blocked.newPage();await fallback.goto(pathToFileURL(path.join(base,'checklist-10-tuan-v4.html')).href);
  await fallback.locator('#W01-01').check();assert.equal(await fallback.locator('#warning').isVisible(),true);
  assert.equal(await fallback.locator('#W01-01').isChecked(),true);
  const legacy={version:5,project:plan.legacy.id,start:'2026-10-12',checked:{'W01-01':true,'W02-01':true,'W03-01':true},notes:{1:'Nhật ký v5'},actualHours:{1:3}};
  const migrated=await browser.newContext();
  await migrated.addInitScript(data=>{try{localStorage.setItem(data.project,JSON.stringify(data));}catch(e){}},legacy);
  const migrationPage=await migrated.newPage();await migrationPage.goto(pathToFileURL(path.join(base,'checklist-10-tuan-v4.html')).href);
  assert.equal(await migrationPage.locator('#W01-01').isChecked(),true);
  assert.equal(await migrationPage.locator('#W02-01').isChecked(),false);
  assert.equal(await migrationPage.locator('#W03-01').isChecked(),false);
  assert.equal(await migrationPage.locator('#notes-1').inputValue(),legacy.notes[1]);
  assert.equal(await migrationPage.locator('#hours-1').inputValue(),'3');
  assert.equal(await migrationPage.evaluate(key=>localStorage.getItem(key),plan.legacy.id),JSON.stringify(legacy));
  // v4 has different task meanings; import only date, notes and actual hours.
  const oldSource=plan.legacy_sources.find(item=>item.version===4);
  const v4={...legacy,version:4,project:oldSource.id};
  await page.locator('#backup-panel').evaluate(el=>el.open=true);
  await page.locator('#paste-json').fill(JSON.stringify(v4));
  await page.locator('#import-text').click();
  assert.equal(await page.locator('input[type=checkbox]:checked').count(),0);
  assert.equal(await page.locator('#notes-1').inputValue(),v4.notes[1]);
  assert.equal(await page.locator('#hours-1').inputValue(),'3');
  assert.match(await page.locator('#date-1').textContent(),/12\/10\/2026/);
  assert.deepEqual(errors,[]);
  const result={scope:'Checklist artifact QA only; not application acceptance',plan_version:6,weeks:10,tasks:60,hours:195,weekly_reporting_guides:10,
   checks:['HTML/JSON match','initially unchecked','date calculation','checkbox/note/hours survive reload','JSON export','paste restore','file restore','wrong plan rejected without state loss','invalid calendar date rejected','mobile without page overflow','print expands and restores weeks','blocked storage warns','10 weekly Word/slide/demo guides','v5 migration retains notes/hours and unchanged tasks; changed web tasks reset; original retained','v4 import retains dates/notes/hours and resets ticks'],browser_errors:errors};
  fs.writeFileSync(path.join(base,'evidence/checklist-10-tuan-v4-validation.json'),JSON.stringify(result,null,2)+'\n');
  console.log(JSON.stringify(result));
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
